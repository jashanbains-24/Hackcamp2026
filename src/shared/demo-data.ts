function community(
  slug: string,
  name: string,
  municipality: string,
  visibility: Community['visibility'],
  adjacentCommunityIds: string[] = [],
): Community {
  return {
    id: `community-${slug}`,
    slug,
    name,
    municipality,
    description: `Neighbour conversations and practical support in ${name}.`,
    visibility,
    adjacentCommunityIds,
    createdAt,
  }
}

